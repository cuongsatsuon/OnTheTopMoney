CREATE TABLE "brand_profiles" (
	"id" uuid PRIMARY KEY DEFAULT uuidv7() NOT NULL,
	"owner_type" text NOT NULL,
	"owner_id" uuid NOT NULL,
	"name" text NOT NULL,
	"slogan" text DEFAULT '' NOT NULL,
	"industry" text DEFAULT '' NOT NULL,
	"tones" text[] DEFAULT '{}'::text[] NOT NULL,
	"formality" integer DEFAULT 60 NOT NULL,
	"pronoun" text DEFAULT '' NOT NULL,
	"emoji" text DEFAULT 'some' NOT NULL,
	"products" jsonb DEFAULT '[]'::jsonb NOT NULL,
	"audience" text DEFAULT '' NOT NULL,
	"colors" text[] DEFAULT '{}'::text[] NOT NULL,
	"hashtags" text[] DEFAULT '{}'::text[] NOT NULL,
	"banned_words" text[] DEFAULT '{}'::text[] NOT NULL,
	"logo_path" text,
	"allowed_domains" text[] DEFAULT '{}'::text[] NOT NULL,
	"created_at" timestamp (3) with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp (3) with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "brand_profiles_owner_unique" UNIQUE("owner_type","owner_id"),
	CONSTRAINT "brand_profiles_owner_type_check" CHECK ("brand_profiles"."owner_type" in ('group', 'page')),
	CONSTRAINT "brand_profiles_emoji_check" CHECK ("brand_profiles"."emoji" in ('none', 'some', 'many')),
	CONSTRAINT "brand_profiles_formality_check" CHECK ("brand_profiles"."formality" between 0 and 100)
);
